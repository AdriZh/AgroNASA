// Shareable scenario links: encode → decode roundtrip, size budget and malformed links.
import { describe, expect, it } from 'vitest';
import type { FarmScenario } from '../src/domain/types';
import { decodeShare, encodeShare, sameScenario, shareUrl, SHARE_MAX_URL, tokenFromHash } from '../src/state/share';
import { DEMO_KAZAKHSTAN, DEMO_SENEGAL } from '../src/state/demo';

const BASE = 'https://example.org/field-shift/';
// null and missing both mean "unknown" for optional inputs, so compare with both removed
const norm = (x: unknown) => JSON.parse(JSON.stringify(x, (_k, v) => (v === null ? undefined : v)));
// ids are regenerated by position; links between fertilizer and its crop season are preserved
const withoutId = (s: FarmScenario): FarmScenario => {
  const hid = new Map(s.history.map((h, k) => [h.id, `h${k + 1}`]));
  return {
    ...s, id: 'x',
    history: s.history.map((h) => ({ ...h, id: hid.get(h.id)! })),
    fertilizer: s.fertilizer.map((f, k) => ({ ...f, id: `f${k + 1}`, cropSeasonId: hid.get(f.cropSeasonId) ?? '' })),
    confirmedInflows: s.confirmedInflows.map((x, k) => ({ ...x, id: `i${k + 1}` })),
  };
};

describe('share links', () => {
  it.each([DEMO_SENEGAL, DEMO_KAZAKHSTAN].map((d) => [d.id, d] as const))('%s: encode → decode roundtrip restores the scenario and the what-if', (_id, demo) => {
    const url = shareUrl(demo, { rainScale: 0.85, dT: 2 }, BASE);
    expect(url.length).toBeLessThan(SHARE_MAX_URL);
    expect(url.startsWith(`${BASE}#/compare?s=`)).toBe(true);
    const r = decodeShare(tokenFromHash(url.slice(url.indexOf('#'))));
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.whatIf).toEqual({ rainScale: 0.85, dT: 2 });
    // ids are regenerated; every field the engine reads is restored exactly
    const strip = (s: FarmScenario) => ({ ...withoutId(s), location: { ...s.location, lat: +s.location.lat.toFixed(4), lon: +s.location.lon.toFixed(4) } });
    expect(norm(strip(r.scenario))).toEqual(norm(strip(demo)));
    expect(sameScenario(r.scenario, demo)).toBe(true);
  });

  it('keeps edits: budget, area, crops, priority, inflows, prices, soil and the usual-plan override', () => {
    const edited: FarmScenario = {
      ...structuredClone(DEMO_SENEGAL), name: 'Édité · ферма 🌾', area: 3.25, areaUnit: 'acre', availableFunds: 250000, reserve: 0, priority: 'return',
      unavailableCrops: ['sesame'], marketCrops: ['millet', 'groundnut', 'cowpea'], allowFallow: true, needsResidue: false,
      confirmedInflows: [{ id: 'zz', date: '2027-08-01', amount: 50000, label: 'Cooperative advance' }],
      priceOverrides: { 'millet:price': 260000, 'groundnut:seed': null }, soil: { texture: 'sandy-loam', labPh: 5.6 },
      baselineOverride: ['millet', 'cowpea'], irrigation: 'yes', irrigationCapacityMm: 120, regionPackId: 'sn-groundnut-basin',
    };
    const r = decodeShare(encodeShare(edited, { rainScale: 0.7, dT: 3 }));
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.scenario.name).toBe(edited.name);
    expect(r.scenario.area).toBe(3.25);
    expect(r.scenario.areaUnit).toBe('acre');
    expect(r.scenario.availableFunds).toBe(250000);
    expect(r.scenario.priority).toBe('return');
    expect(r.scenario.unavailableCrops).toEqual(['sesame']);
    expect(r.scenario.marketCrops).toEqual(['millet', 'groundnut', 'cowpea']);
    expect(r.scenario.confirmedInflows).toEqual([{ id: 'i1', date: '2027-08-01', amount: 50000, label: 'Cooperative advance' }]);
    expect(r.scenario.priceOverrides).toEqual(edited.priceOverrides);
    expect(r.scenario.soil).toEqual({ texture: 'sandy-loam', labPh: 5.6, labSocPct: null });
    expect(r.scenario.baselineOverride).toEqual(['millet', 'cowpea']);
    expect(r.scenario.irrigation).toBe('yes');
    expect(r.scenario.irrigationCapacityMm).toBe(120);
    expect(r.scenario.allowFallow).toBe(true);
    expect(r.scenario.needsResidue).toBe(false);
    expect(r.scenario.fertilizer.map((f) => f.cropSeasonId)).toEqual(['h1', 'h1', 'h2', 'h3']);
    expect(r.whatIf).toEqual({ rainScale: 0.7, dT: 3 });
  });

  it('stays under the URL budget even for a long farm history (drops notes, fertilizer, then old seasons)', () => {
    const big: FarmScenario = structuredClone(DEMO_SENEGAL);
    for (let k = 0; k < 20; k++) big.history.push({ ...big.history[0], id: `x${k}`, year: 2000 + k, notes: 'A long free-text note about this season. '.repeat(3) });
    for (let k = 0; k < 20; k++) big.fertilizer.push({ ...big.fertilizer[0], id: `y${k}`, cropSeasonId: `x${k}` });
    const url = shareUrl(big, { rainScale: 0.85, dT: 2 }, BASE);
    expect(url.length).toBeLessThan(SHARE_MAX_URL);
    const r = decodeShare(tokenFromHash(url.slice(url.indexOf('#'))));
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    // the most recent seasons (which the engine reads) survive
    expect(r.scenario.history.length).toBeGreaterThanOrEqual(4);
    expect(Math.max(...r.scenario.history.map((h) => h.year))).toBe(2026);
  });

  it.each([
    ['empty', ''],
    ['not base64', '%%%not-base64!!'],
    ['truncated', encodeShare(DEMO_SENEGAL).slice(0, 40)],
    ['valid base64, not JSON', btoa('hello world').replace(/=+$/, '')],
    ['JSON array', btoa('[1,2,3]').replace(/=+$/, '')],
    ['wrong version', btoa(JSON.stringify({ v: 99 })).replace(/=+$/, '')],
    ['bad latitude', btoa(JSON.stringify({ ...JSON.parse(new TextDecoder().decode(Uint8Array.from(atob(encodeShare(DEMO_SENEGAL).replace(/-/g, '+').replace(/_/g, '/') + '==='.slice((encodeShare(DEMO_SENEGAL).length + 3) % 4)), (c) => c.charCodeAt(0)))), l: [123, 0] })).replace(/=+$/, '')],
    ['zero area', btoa(JSON.stringify({ v: 1, n: 'x', l: [1, 1], a: [0, 'ha'], cu: 'USD', b: [1, 0], y: 2027, ir: ['no', 0], lb: 'low', f: '00', pr: 'cost' })).replace(/=+$/, '')],
    ['injected types', btoa(JSON.stringify({ v: 1, n: { evil: true }, l: [1, 1], a: [1, 'ha'], cu: 'USD', b: [1, 0], y: 2027, ir: ['no', 0], lb: 'low', f: '00', pr: 'cost' })).replace(/=+$/, '')],
  ])('malformed link (%s) is rejected politely, never throws', (_name, token) => {
    const r = decodeShare(token);
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.error.length).toBeGreaterThan(3);
  });

  it('unknown crops are dropped instead of crashing the UI; bad what-if values fall back to the record', () => {
    const t = btoa(JSON.stringify({ v: 1, n: 'x', l: [14.7, -16.4], a: [1, 'ha'], cu: 'XOF', b: [1000, 0], y: 2027, ir: ['no', 0], lb: 'high', f: '00', pr: 'cost', h: [['mandrake', 2025], ['millet', 2026]], bo: ['mandrake', 'millet'], w: [0.01, 99] })).replace(/=+$/, '');
    const r = decodeShare(t);
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.scenario.history.map((h) => h.cropId)).toEqual(['millet']);
    expect(r.scenario.baselineOverride).toBeNull();
    expect(r.whatIf).toEqual({ rainScale: 0.7, dT: 3 });
  });

  it('reads the token from the hash; routes without a query have none', () => {
    expect(tokenFromHash('#/compare?s=abc_-')).toBe('abc_-');
    expect(tokenFromHash('#/compare')).toBeNull();
    expect(tokenFromHash('')).toBeNull();
  });
});
